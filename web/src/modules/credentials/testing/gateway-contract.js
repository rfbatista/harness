// The CredentialGateway contract (../domain/ports.js), run by every
// implementation. A fake that passes it behaves like the server as far as the
// Git credentials page, the Repositories page and their tests can tell.

import { Codes } from "../../../shared/domain/errors.js";
import { FeedStatus } from "../../../shared/domain/feed.js";
import { flush } from "../../../shared/testing/doubles.js";
import { assert, test } from "../../../shared/testing/test.js";
import { PASSPHRASE } from "../infrastructure/memory-gateway.js";
import { ENCRYPTED_KEY, PRIVATE_KEY, REPOSITORIES, SECRET_TOKEN, credentialDTO, makeCredential, makeKey, repositoryCredentialDTO } from "./fixtures.js";

/**
 * @typedef {object} Subject
 * @property {import("../domain/ports.js").CredentialGateway} gateway
 * @property {(on?: boolean) => void} lock  the server loses its encryption key
 */

/**
 * @param {string} name
 * @param {(world: object) => Subject} makeSubject
 */
export function credentialGatewayContract(name, makeSubject) {
  const contract = (title, fn) => test(`${name} · ${title}`, fn);
  const names = (list) => list.map((c) => c.name);

  const world = (extra = {}) => ({
    credentials: [
      makeCredential(),
      makeKey(),
      makeCredential({ id: "gc-gitlab", name: "Gitlab", host: "gitlab.example.com", isDefault: false }),
      makeCredential({ id: "gc-spare", name: "spare-token", isDefault: false }),
    ],
    repositories: REPOSITORIES.map((r) => ({ ...r })),
    ...extra,
  });

  contract("lists by host, then name ignoring case; times are Dates", async () => {
    const { gateway } = makeSubject(world());
    const list = await gateway.list();
    assert.deepEqual(names(list), ["laptop-key", "spare-token", "work-token", "Gitlab"]);
    const work = list.find((c) => c.id === "gc-work");
    assert.deepEqual([work.kind, work.host, work.username, work.fingerprint, work.publicKey, work.isDefault, work.lastUsedAt], ["https_token", "github.com", "x-access-token", "…1234", null, true, null]);
    assert.ok(work.createdAt instanceof Date && work.updatedAt instanceof Date);
    assert.ok(list.find((c) => c.id === "gc-key").publicKey.startsWith("ssh-ed25519 "));
  });

  contract("creates a token: the host is normalised, the username defaults, and the token never comes back", async () => {
    const { gateway } = makeSubject(world());
    const c = await gateway.create({ name: "  ci  ", kind: "https_token", host: "https://GitHub.com/acme/harness", token: SECRET_TOKEN });
    assert.deepEqual([c.name, c.host, c.username, c.fingerprint, c.publicKey, c.isDefault], ["ci", "github.com", "x-access-token", "…1234", null, false]);
    assert.ok(!JSON.stringify(c).includes(SECRET_TOKEN), "the answer has no token");
    assert.ok(!JSON.stringify(await gateway.list()).includes(SECRET_TOKEN), "nor the list");
    const named = await gateway.create({ name: "bot", kind: "https_token", host: "github.com", username: "acme-bot", token: "t-9876" });
    assert.deepEqual([named.username, named.fingerprint], ["acme-bot", "…9876"]);
  });

  contract("creates an SSH key generated by the server, or from a private key (an encrypted one with its passphrase)", async () => {
    const { gateway } = makeSubject(world());
    const made = await gateway.create({ name: "gen", kind: "ssh_key", host: "github.com", generate: true });
    assert.deepEqual([made.kind, made.username], ["ssh_key", "git"]);
    assert.ok(made.publicKey?.startsWith("ssh-ed25519 ") && made.fingerprint.startsWith("SHA256:"));
    const imported = await gateway.create({ name: "imported", kind: "ssh_key", host: "github.com", privateKey: PRIVATE_KEY });
    assert.ok(imported.publicKey && !JSON.stringify(imported).includes("PRIVATE KEY"));
    await assert.rejects(gateway.create({ name: "locked-key", kind: "ssh_key", host: "github.com", privateKey: ENCRYPTED_KEY }), Codes.GIT_CREDENTIAL_INVALID_KEY);
    await assert.rejects(gateway.create({ name: "locked-key", kind: "ssh_key", host: "github.com", privateKey: ENCRYPTED_KEY, passphrase: "wrong" }), Codes.GIT_CREDENTIAL_INVALID_KEY);
    const opened = await gateway.create({ name: "locked-key", kind: "ssh_key", host: "github.com", privateKey: ENCRYPTED_KEY, passphrase: PASSPHRASE });
    assert.equal(opened.name, "locked-key");
    await assert.rejects(gateway.create({ name: "junk", kind: "ssh_key", host: "github.com", privateKey: "not a key" }), Codes.GIT_CREDENTIAL_INVALID_KEY);
  });

  contract("refuses a missing name, host or token, and a name taken in any case", async () => {
    const { gateway } = makeSubject(world());
    await assert.rejects(gateway.create({ name: " ", kind: "https_token", host: "github.com", token: "t" }), Codes.INVALID_INPUT);
    await assert.rejects(gateway.create({ name: "x", kind: "https_token", host: "https:///", token: "t" }), Codes.INVALID_INPUT);
    await assert.rejects(gateway.create({ name: "x", kind: "https_token", host: "github.com" }), Codes.INVALID_INPUT);
    await assert.rejects(gateway.create({ name: "WORK-TOKEN", kind: "https_token", host: "github.com", token: "t" }), Codes.GIT_CREDENTIAL_NAME_TAKEN);
    assert.equal((await gateway.list()).length, 4, "nothing was added");
  });

  contract("one default per host and kind: a new default takes the flag from the old one", async () => {
    const { gateway } = makeSubject(world());
    const next = await gateway.create({ name: "new-default", kind: "https_token", host: "github.com", token: "t-0001", isDefault: true });
    const list = await gateway.list();
    assert.deepEqual(list.filter((c) => c.isDefault).map((c) => c.id), [next.id]);
    await gateway.update({ credentialId: "gc-key", isDefault: true });
    assert.deepEqual((await gateway.list()).filter((c) => c.isDefault).map((c) => c.name).sort(), ["laptop-key", "new-default"], "keys and tokens keep their own default");
  });

  contract("updates: absent fields and an empty secret keep their value; a new token changes the fingerprint; un-defaulting clears the flag", async () => {
    const { gateway } = makeSubject(world());
    const renamed = await gateway.update({ credentialId: "gc-work", name: "Work", token: "" });
    assert.deepEqual([renamed.name, renamed.host, renamed.fingerprint, renamed.isDefault], ["Work", "github.com", "…1234", true]);
    const rotated = await gateway.update({ credentialId: "gc-work", token: "ghp_rotated5678" });
    assert.equal(rotated.fingerprint, "…5678");
    const plain = await gateway.update({ credentialId: "gc-work", isDefault: false });
    assert.equal(plain.isDefault, false);
    await assert.rejects(gateway.update({ credentialId: "gc-work", name: "laptop-KEY" }), Codes.GIT_CREDENTIAL_NAME_TAKEN);
    await assert.rejects(gateway.update({ credentialId: "ghost", name: "x" }), Codes.GIT_CREDENTIAL_NOT_FOUND);
    await assert.rejects(gateway.update({ credentialId: "gc-key", privateKey: "junk" }), Codes.GIT_CREDENTIAL_INVALID_KEY);
  });

  contract("a host change on a pinned credential is refused, naming the pinned repositories", async () => {
    const { gateway } = makeSubject(world());
    await gateway.setRepositoryCredential("r-https", "gc-spare");
    const err = await assert.rejects(gateway.update({ credentialId: "gc-spare", host: "gitlab.example.com" }), Codes.GIT_CREDENTIAL_HOST_MISMATCH);
    assert.deepEqual(err.details?.repositories, [{ id: "r-https", name: "harness" }]);
    const same = await gateway.update({ credentialId: "gc-spare", host: "GitHub.com" });
    assert.equal(same.host, "github.com", "the same host, written otherwise, is no change");
  });

  contract("deleting unpins the repositories pinned to it; an unknown id is NOT_FOUND", async () => {
    const { gateway } = makeSubject(world());
    await gateway.setRepositoryCredential("r-https", "gc-spare");
    await gateway.remove("gc-spare");
    assert.ok(!(await gateway.list()).some((c) => c.id === "gc-spare"));
    const rc = await gateway.getRepositoryCredential("r-https");
    assert.deepEqual([rc.credentialId, rc.resolved?.id], [null, "gc-work"], "back to automatic");
    await assert.rejects(gateway.remove("gc-spare"), Codes.GIT_CREDENTIAL_NOT_FOUND);
  });

  contract("test signs in against a repository's origin, or the host; a refusal is ok:false, never an error", async () => {
    const { gateway } = makeSubject(world({ refuse: (c) => (c.id === "gc-spare" ? "Bad credentials" : "") }));
    const viaRepo = await gateway.test("gc-work", "r-https");
    assert.deepEqual([viaRepo.ok, viaRepo.checkedUrl], [true, "https://github.com/acme/harness.git"]);
    assert.ok(viaRepo.message);
    assert.ok((await gateway.list()).find((c) => c.id === "gc-work").lastUsedAt instanceof Date, "success records last use");
    assert.equal((await gateway.test("gc-key")).ok, true, "a key is tested with ssh -T on its host");
    assert.equal((await gateway.test("gc-work")).ok, true, "a GitHub token is tested against the GitHub API");
    const elsewhere = await gateway.test("gc-gitlab");
    assert.deepEqual([elsewhere.ok, elsewhere.message], [false, "pick a repository to test this token against"]);
    const refused = await gateway.test("gc-spare", "r-https");
    assert.deepEqual([refused.ok, refused.message], [false, "Bad credentials"]);
    assert.equal((await gateway.list()).find((c) => c.id === "gc-spare").lastUsedAt, null, "a refusal records nothing");
    await assert.rejects(gateway.test("ghost"), Codes.GIT_CREDENTIAL_NOT_FOUND);
    await assert.rejects(gateway.test("gc-work", "ghost"), Codes.REPOSITORY_NOT_FOUND);
  });

  contract("the identity starts unset, is saved trimmed, and needs a name and an email with one @", async () => {
    const { gateway } = makeSubject(world());
    assert.equal(await gateway.getIdentity(), null);
    const saved = await gateway.updateIdentity({ name: " Ada ", email: " ada@example.com " });
    assert.deepEqual(saved, { name: "Ada", email: "ada@example.com" });
    assert.deepEqual(await gateway.getIdentity(), saved);
    await assert.rejects(gateway.updateIdentity({ name: "", email: "a@b" }), Codes.INVALID_INPUT);
    await assert.rejects(gateway.updateIdentity({ name: "Ada", email: "a@b@c" }), Codes.INVALID_INPUT);
  });

  contract("a project's repositories resolve: their pin, else the default or only credential of the origin's host and kind", async () => {
    const { gateway } = makeSubject(world());
    const all = await gateway.listRepositoryCredentials("p1");
    assert.deepEqual(
      all.map((rc) => [rc.repositoryId, rc.credentialId, rc.resolved?.id ?? null, rc.remoteUrl]),
      [
        ["r-https", null, "gc-work", "https://github.com/acme/harness.git"],
        ["r-ssh", null, "gc-key", "git@github.com:acme/infra.git"],
        ["r-gitlab", null, "gc-gitlab", "https://gitlab.example.com/acme/mirror.git"],
        ["r-local", null, null, null],
      ],
    );
    assert.equal((await gateway.getRepositoryCredential("r-other")).resolved?.id, "gc-work");
    await assert.rejects(gateway.listRepositoryCredentials("ghost"), Codes.PROJECT_NOT_FOUND);
    await assert.rejects(gateway.getRepositoryCredential("ghost"), Codes.REPOSITORY_NOT_FOUND);
  });

  contract("pins a credential of the origin's host and kind, or none; a repository without an origin takes any", async () => {
    const { gateway } = makeSubject(world());
    const pinned = await gateway.setRepositoryCredential("r-https", "gc-spare");
    assert.deepEqual([pinned.credentialId, pinned.resolved?.id], ["gc-spare", "gc-spare"]);
    await assert.rejects(gateway.setRepositoryCredential("r-https", "gc-key"), Codes.GIT_CREDENTIAL_KIND_MISMATCH);
    await assert.rejects(gateway.setRepositoryCredential("r-https", "gc-gitlab"), Codes.GIT_CREDENTIAL_HOST_MISMATCH);
    await assert.rejects(gateway.setRepositoryCredential("r-https", "ghost"), Codes.GIT_CREDENTIAL_NOT_FOUND);
    await assert.rejects(gateway.setRepositoryCredential("ghost", null), Codes.REPOSITORY_NOT_FOUND);
    assert.equal((await gateway.setRepositoryCredential("r-local", "gc-key")).credentialId, "gc-key");
    const automatic = await gateway.setRepositoryCredential("r-https", null);
    assert.deepEqual([automatic.credentialId, automatic.resolved?.id], [null, "gc-work"]);
  });

  contract("a locked store still lists, deletes, renames, pins and saves the identity; what needs a secret is STORE_LOCKED", async () => {
    const { gateway, lock } = makeSubject(world());
    lock();
    assert.equal((await gateway.list()).length, 4);
    await gateway.update({ credentialId: "gc-work", name: "renamed", isDefault: true });
    await gateway.updateIdentity({ name: "Ada", email: "ada@example.com" });
    await gateway.setRepositoryCredential("r-https", "gc-spare");
    await gateway.remove("gc-gitlab");
    await assert.rejects(gateway.create({ name: "new", kind: "https_token", host: "github.com", token: "t" }), Codes.GIT_CREDENTIAL_STORE_LOCKED);
    await assert.rejects(gateway.create({ name: "new", kind: "ssh_key", host: "github.com", generate: true }), Codes.GIT_CREDENTIAL_STORE_LOCKED);
    await assert.rejects(gateway.update({ credentialId: "gc-work", token: "t-2" }), Codes.GIT_CREDENTIAL_STORE_LOCKED);
    await assert.rejects(gateway.test("gc-work"), Codes.GIT_CREDENTIAL_STORE_LOCKED);
    lock(false);
    assert.equal((await gateway.test("gc-work")).ok, true);
  });

  contract("decodes the pages' seeds, the API's shapes; a bad one is BAD_RESPONSE", () => {
    const { gateway } = makeSubject({});
    const page = gateway.decodePageSeed({ credentials: [credentialDTO(makeCredential())], identity: { name: "Ada", email: "ada@example.com" } });
    assert.deepEqual([names(page.credentials), page.identity], [["work-token"], { name: "Ada", email: "ada@example.com" }]);
    assert.equal(gateway.decodePageSeed({ credentials: [], identity: null }).identity, null);
    assert.throws(() => gateway.decodePageSeed({ identity: null }), Codes.BAD_RESPONSE);
    const rc = { repositoryId: "r-https", credentialId: null, resolved: makeCredential(), remoteUrl: "https://github.com/acme/harness.git" };
    const repos = gateway.decodeRepositoriesSeed({ project_id: "p1", credentials: [], repositories: [repositoryCredentialDTO(rc)] });
    assert.deepEqual([repos.projectId, repos.repositories[0].resolved?.id, repos.repositories[0].credentialId], ["p1", "gc-work", null]);
    assert.throws(() => gateway.decodeRepositoriesSeed({ credentials: [], repositories: [] }), Codes.BAD_RESPONSE);
  });

  contract("follow reports live, streams credential and identity changes, the person's own included, and stops when closed", async () => {
    const { gateway } = makeSubject(world());
    const changes = [];
    const statuses = [];
    const close = gateway.follow((c) => changes.push(c), (s) => statuses.push(s));
    await flush();
    assert.ok(statuses.includes(FeedStatus.LIVE));
    const made = await gateway.create({ name: "ci", kind: "https_token", host: "github.com", token: SECRET_TOKEN });
    await gateway.update({ credentialId: made.id, name: "ci-2" });
    await gateway.remove(made.id);
    await gateway.updateIdentity({ name: "Ada", email: "ada@example.com" });
    await flush();
    assert.deepEqual(
      changes.map((c) => (c.kind === "upsert" ? ["upsert", c.credential.name] : c.kind === "deleted" ? ["deleted", c.id] : ["identity", c.identity.name])),
      [["upsert", "ci"], ["upsert", "ci-2"], ["deleted", made.id], ["identity", "Ada"]],
    );
    assert.ok(!JSON.stringify(changes).includes(SECRET_TOKEN), "no change carries the secret");
    close();
    await gateway.updateIdentity({ name: "Late", email: "l@x" });
    await flush();
    assert.equal(changes.length, 4, "nothing after close");
  });

  contract("a change is streamed before it is answered", async () => {
    let release;
    const subject = makeSubject(world({ beforeAnswer: () => new Promise((r) => (release = r)) }));
    const changes = [];
    const close = subject.gateway.follow((c) => changes.push(c), () => {});
    await flush();
    let answered = false;
    const pending = subject.gateway.update({ credentialId: "gc-work", name: "renamed" }).then((c) => ((answered = true), c));
    await flush();
    assert.deepEqual([changes.length, answered], [1, false], "the echo arrives while the POST is in flight");
    release();
    assert.equal((await pending).name, "renamed");
    close();
  });
}
