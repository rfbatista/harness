package repoarch

import (
	"bytes"

	"gopkg.in/yaml.v3"

	"operators-mcp/internal/domain"
)

// fileHeader starts every architecture file.
const fileHeader = "# Generated by the harness from the repository architecture. Edit it in the harness; changes here are not read back yet.\n"

// ArchitectureYAML is the record's YAML form: the content of
// .harness/architecture.yaml and of the read-only file in the virtual shell.
// The same record always yields the same bytes: keys in the schema's order,
// map keys sorted, multi-line text as block scalars.
func ArchitectureYAML(record domain.ArchitectureRecord) ([]byte, error) {
	record.Normalize()
	var buf bytes.Buffer
	buf.WriteString(fileHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(record); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
