// Package contextmap generates the context map of a repository (ADR 0013's
// Learn layer): a size-capped markdown map built without an LLM from the
// default branch, stamped with its commit, held by the harness and delivered
// beside the hand-written AGENTS.md, never committed.
package contextmap

import (
	"encoding/json"
	"fmt"
	"path"
	"sort"
	"strings"
)

// MaxLines is the most lines a map has.
const MaxLines = 300

// layoutDepth is how deep the layout lists directories.
const layoutDepth = 2

// Gate is a build, test or lint command of the repository.
type Gate struct{ Kind, Command string }

// Layer is a layer of the repository's architecture record and its folder.
type Layer struct{ Name, Folder string }

// Input is what a map is generated from: the default branch's files, read
// through Read (false when the branch has no such file), never the checkout.
type Input struct {
	Repository, Branch, Commit string
	Files                      []string
	Read                       func(path string) ([]byte, bool)
	Gates                      []Gate
	// Instructions are the paths of the repository's instruction files.
	Instructions []string
	Layers       []Layer
}

// Generate is the map of in. Commands, entry points and where to look are
// never cut; the layout takes the rest of the line cap.
func Generate(in Input) string {
	head := []string{
		"# Context map: " + in.Repository,
		"",
		fmt.Sprintf("Generated by the harness from %s @ %s, without an LLM. Not committed.", in.Branch, in.Commit),
	}
	var tail []string
	if len(in.Gates) > 0 {
		tail = append(tail, "", "## Commands", "")
		for _, g := range in.Gates {
			tail = append(tail, fmt.Sprintf("- %s: `%s`", g.Kind, g.Command))
		}
	}
	if entries := entryPoints(in); len(entries) > 0 {
		tail = append(tail, "", "## Entry points", "")
		tail = append(tail, entries...)
	}
	if look := whereToLook(in); len(look) > 0 {
		tail = append(tail, "", "## Where to look", "")
		tail = append(tail, look...)
	}
	budget := MaxLines - len(head) - len(tail) - 3 // blank line, heading, blank line
	layout := layoutLines(in.Files, budget)
	lines := append(head, "", "## Layout", "")
	lines = append(lines, layout...)
	lines = append(lines, tail...)
	return strings.Join(lines, "\n") + "\n"
}

// layoutLines is one line per directory down to layoutDepth, with the count
// of files below it, cut to budget lines.
func layoutLines(files []string, budget int) []string {
	counts := map[string]int{}
	for _, f := range files {
		parts := strings.Split(f, "/")
		for d := 1; d <= layoutDepth && d < len(parts); d++ {
			counts[strings.Join(parts[:d], "/")+"/"]++
		}
	}
	dirs := make([]string, 0, len(counts))
	for d := range counts {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	var out []string
	for i, d := range dirs {
		if len(out) >= budget-1 && i < len(dirs)-1 {
			out = append(out, fmt.Sprintf("- … %d more directories", len(dirs)-i))
			return out
		}
		out = append(out, fmt.Sprintf("- `%s` — %s", d, plural(counts[d], "file")))
	}
	return out
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return fmt.Sprintf("%d %ss", n, word)
}

// entryPoints are the places a run or a build starts: main packages, the
// "main" and "bin" of a package.json, and the build files at the root.
func entryPoints(in Input) []string {
	var out []string
	files := append([]string(nil), in.Files...)
	sort.Strings(files)
	for _, f := range files {
		switch {
		case path.Base(f) == "main.go":
			out = append(out, fmt.Sprintf("- `%s`", f))
		case path.Base(f) == "package.json" && in.Read != nil:
			if raw, ok := in.Read(f); ok {
				var pkg struct {
					Main string `json:"main"`
				}
				if json.Unmarshal(raw, &pkg) == nil && pkg.Main != "" {
					out = append(out, fmt.Sprintf("- `%s` (%s main)", path.Join(path.Dir(f), pkg.Main), f))
				}
			}
		case f == "Makefile" || f == "check.sh" || f == "Dockerfile":
			out = append(out, fmt.Sprintf("- `%s`", f))
		}
	}
	return out
}

// whereToLook points to the instruction files and the architecture layers.
func whereToLook(in Input) []string {
	var out []string
	for _, p := range in.Instructions {
		out = append(out, fmt.Sprintf("- `%s` — hand-written guidance; read it, it is not repeated here", p))
	}
	for _, l := range in.Layers {
		out = append(out, fmt.Sprintf("- `%s/` — layer %s", strings.TrimSuffix(l.Folder, "/"), l.Name))
	}
	return out
}
