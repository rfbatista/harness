const (
	fileStateTitle = `document.querySelector('[data-file-state-title]')?.textContent.trim() ?? ''`
	yamlText       = `document.querySelector('[data-yaml]')?.textContent ?? ''`
)

func exportButtonEnabled() string {
	return `(() => { const b = document.querySelector('[data-export]'); return !!b && b.checkVisibility() && !b.disabled })()`
}

// The Output tab shows where the file is, how it stands against the saved
// record and the YAML the export writes.
func TestArchitectureOutputShowsTheFileStateAndTheYaml(t *testing.T) {
	rig := newArchRig(t)
	rig.api.seed(savedRecord())
	rig.api.export = map[string]any{
		"state": "database_ahead", "path": ".harness/architecture.yaml",
		"exported_version": 0, "exported_commit": "9f8e7d6c5b4a", "exported_at": "2026-10-20T10:00:00Z",
	}
	var title, yaml, path, last string
	rig.run(t,
		chromedp.EmulateViewport(1280, 900),
		chromedp.Navigate(rig.url("")),
		poll(`document.querySelectorAll('[role=tab]').length === 7`),
		clickTab("Output"),
		poll(`location.pathname.endsWith('/architecture/file')`),
		poll(`document.querySelector('[data-yaml]')?.textContent.includes('layers:')`),
		chromedp.Evaluate(fileStateTitle, &title),
		chromedp.Evaluate(yamlText, &yaml),
		chromedp.Evaluate(`document.querySelector('[data-file-path]').textContent.trim()`, &path),
		chromedp.Evaluate(`document.querySelector('[data-last-export]').textContent.replace(/\s+/g, ' ').trim()`, &last),
	)
	if title != "Database ahead of the file" {
		t.Fatalf("state = %q", title)
	}
	if path != ".harness/architecture.yaml" {
		t.Fatalf("path = %q", path)
	}
	if !strings.Contains(last, "commit 9f8e7d6") {
		t.Fatalf("last export = %q", last)
	}
	for _, want := range []string{
		"# Generated by the harness from the repository architecture. Edit it in the harness; changes here are not read back yet.\n",
		"version: 1\nrepository: harness\n",
		"layers:\n  - name: domain\n    match:\n      folder: internal/domain\n",
		"      regex: '^internal/adapter/'\n",
		"rules:\n  - id: stay-in-your-layer\n    kind: edit_outside_layer\n    mode: blocking\n",
	} {
		if !strings.Contains(yaml, want) {
			t.Fatalf("the YAML lacks %q:\n%s", want, yaml)
		}
	}
	if strings.Index(yaml, "\ninstructions:") > strings.Index(yaml, "\nlayers:") || strings.Index(yaml, "\nlayers:") > strings.Index(yaml, "\nrules:") {
		t.Fatalf("the YAML keys are out of order:\n%s", yaml)
	}
}

