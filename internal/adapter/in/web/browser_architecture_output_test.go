func contains(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

// A dirty checkout and a wrong branch each explain themselves and say what to do.
func TestArchitectureOutputExplainsEachExportRefusal(t *testing.T) {
	for code, want := range map[string][]string{
		"CHECKOUT_DIRTY": {"uncommitted changes", "Commit or stash"},
		"WRONG_BRANCH":   {"not on its default branch", "Switch the checkout"},
	} {
		t.Run(code, func(t *testing.T) {
			rig := newArchRig(t)
			rig.api.seed(savedRecord())
			rig.api.exportErr = code
			var text, got string
			rig.run(t,
				chromedp.EmulateViewport(1280, 900),
				chromedp.Navigate(rig.url("/file")),
				poll(exportButtonEnabled()),
				chromedp.Click(`[data-export]`, chromedp.ByQuery),
				poll(`!!document.querySelector('[data-export-refusal]')`),
				chromedp.Evaluate(`document.querySelector('[data-export-refusal]').textContent.replace(/\s+/g, ' ')`, &text),
				chromedp.Evaluate(`document.querySelector('[data-export-refusal]').dataset.code`, &got),
			)
			for _, w := range want {
				if !strings.Contains(text, w) {
					t.Errorf("%s says %q, which lacks %q", code, text, w)
				}
			}
			if got != code {
				t.Errorf("code = %q", got)
			}
			var shown bool
			rig.run(t, chromedp.Evaluate(`!document.querySelector('[data-export-result]')`, &shown))
			if !shown {
				t.Error("a refused export shows a result")
			}
		})
	}
}

