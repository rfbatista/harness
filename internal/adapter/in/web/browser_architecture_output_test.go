const (
	fileStateTitle = `document.querySelector('[data-file-state-title]')?.textContent.trim() ?? ''`
	yamlText       = `document.querySelector('[data-yaml]')?.textContent ?? ''`
)

func exportButtonEnabled() string {
	return `(() => { const b = document.querySelector('[data-export]'); return !!b && b.checkVisibility() && !b.disabled })()`
}

// The Output tab shows where the file is, how it stands against the saved
// record and the YAML the export writes.
func TestArchitectureOutputShowsTheFileStateAndTheYaml(t *testing.T) {
	rig := newArchRig(t)
	rig.api.seed(savedRecord())
	rig.api.export = map[string]any{
		"state": "database_ahead", "path": ".harness/architecture.yaml",
		"exported_version": 0, "exported_commit": "9f8e7d6c5b4a", "exported_at": "2026-10-20T10:00:00Z",
	}
	var title, yaml, path, last string
	rig.run(t,
		chromedp.EmulateViewport(1280, 900),
		chromedp.Navigate(rig.url("")),
		poll(`document.querySelectorAll('[role=tab]').length === 7`),
		clickTab("Output"),
		poll(`location.pathname.endsWith('/architecture/file')`),
		poll(`document.querySelector('[data-yaml]')?.textContent.includes('layers:')`),
		chromedp.Evaluate(fileStateTitle, &title),
		chromedp.Evaluate(yamlText, &yaml),
		chromedp.Evaluate(`document.querySelector('[data-file-path]').textContent.trim()`, &path),
		chromedp.Evaluate(`document.querySelector('[data-last-export]').textContent.replace(/\s+/g, ' ').trim()`, &last),
	)
	if title != "Database ahead of the file" {
		t.Fatalf("state = %q", title)
	}
	if path != ".harness/architecture.yaml" {
		t.Fatalf("path = %q", path)
	}
	if !strings.Contains(last, "commit 9f8e7d6") {
		t.Fatalf("last export = %q", last)
	}
	for _, want := range []string{
		"# Generated by the harness from the repository architecture. Edit it in the harness; changes here are not read back yet.\n",
		"version: 1\nrepository: harness\n",
		"layers:\n  - name: domain\n    match:\n      folder: internal/domain\n",
		"      regex: '^internal/adapter/'\n",
		"rules:\n  - id: stay-in-your-layer\n    kind: edit_outside_layer\n    mode: blocking\n",
	} {
		if !strings.Contains(yaml, want) {
			t.Fatalf("the YAML lacks %q:\n%s", want, yaml)
		}
	}
	if strings.Index(yaml, "\ninstructions:") > strings.Index(yaml, "\nlayers:") || strings.Index(yaml, "\nlayers:") > strings.Index(yaml, "\nrules:") {
		t.Fatalf("the YAML keys are out of order:\n%s", yaml)
	}
}

// Every export state has its own words.
func TestArchitectureOutputSaysEachExportStateInWords(t *testing.T) {
	for state, want := range map[string]string{
		"never_exported": "Never exported",
		"in_sync":        "In sync",
		"database_ahead": "Database ahead of the file",
		"edited_outside": "File edited outside",
		"file_invalid":   "File invalid",
	} {
		t.Run(state, func(t *testing.T) {
			rig := newArchRig(t)
			rig.api.seed(savedRecord())
			rig.api.export = map[string]any{"state": state, "path": ".harness/architecture.yaml"}
			var title string
			rig.run(t,
				chromedp.EmulateViewport(1280, 900),
				chromedp.Navigate(rig.url("/file")),
				poll(`!!document.querySelector('[data-file-state-title]')?.checkVisibility()`),
				chromedp.Evaluate(fileStateTitle, &title),
			)
			if title != want {
				t.Fatalf("%s reads %q, want %q", state, title, want)
			}
		})
	}
}

// Export commits the file, shows the commit and the state becomes in sync.
func TestArchitectureOutputExportShowsTheCommitAndTheStateBecomesInSync(t *testing.T) {
	rig := newArchRig(t)
	rig.api.seed(savedRecord())
	var title, result, last string
	rig.run(t,
		chromedp.EmulateViewport(1280, 900),
		chromedp.Navigate(rig.url("/file")),
		poll(exportButtonEnabled()),
		chromedp.Click(`[data-export]`, chromedp.ByQuery),
		poll(`!!document.querySelector('[data-export-result]')`),
		poll(`document.querySelector('[data-file-state-title]')?.textContent.trim() === 'In sync'`),
		chromedp.Evaluate(fileStateTitle, &title),
		chromedp.Evaluate(`document.querySelector('[data-export-result]').textContent.replace(/\s+/g, ' ').trim()`, &result),
		chromedp.Evaluate(`document.querySelector('[data-last-export]').textContent.replace(/\s+/g, ' ').trim()`, &last),
	)
	if !strings.Contains(result, "abc1234") {
		t.Fatalf("result = %q", result)
	}
	if !strings.Contains(last, "commit abc1234") {
		t.Fatalf("last export = %q", last)
	}
	if got := rig.api.called(); !contains(got, "export_repository_architecture") {
		t.Fatalf("calls = %v", got)
	}
}

func contains(xs []string, s string) bool {
	for _, x := range xs {
		if x == s {
			return true
		}
	}
	return false
}

// A dirty checkout and a wrong branch each explain themselves and say what to do.
func TestArchitectureOutputExplainsEachExportRefusal(t *testing.T) {
	for code, want := range map[string][]string{
		"CHECKOUT_DIRTY": {"uncommitted changes", "Commit or stash"},
		"WRONG_BRANCH":   {"not on its default branch", "Switch the checkout"},
	} {
		t.Run(code, func(t *testing.T) {
			rig := newArchRig(t)
			rig.api.seed(savedRecord())
			rig.api.exportErr = code
			var text, got string
			rig.run(t,
				chromedp.EmulateViewport(1280, 900),
				chromedp.Navigate(rig.url("/file")),
				poll(exportButtonEnabled()),
				chromedp.Click(`[data-export]`, chromedp.ByQuery),
				poll(`!!document.querySelector('[data-export-refusal]')`),
				chromedp.Evaluate(`document.querySelector('[data-export-refusal]').textContent.replace(/\s+/g, ' ')`, &text),
				chromedp.Evaluate(`document.querySelector('[data-export-refusal]').dataset.code`, &got),
			)
			for _, w := range want {
				if !strings.Contains(text, w) {
					t.Errorf("%s says %q, which lacks %q", code, text, w)
				}
			}
			if got != code {
				t.Errorf("code = %q", got)
			}
			var shown bool
			rig.run(t, chromedp.Evaluate(`!document.querySelector('[data-export-result]')`, &shown))
			if !shown {
				t.Error("a refused export shows a result")
			}
		})
	}
}

// Export is not offered while the draft is unsaved, and the YAML stays the saved version.
func TestArchitectureOutputExportIsNotOfferedWhileTheDraftIsUnsaved(t *testing.T) {
	rig := newArchRig(t)
	rig.api.seed(savedRecord())
	var note, yaml string
	rig.run(t,
		chromedp.EmulateViewport(1280, 900),
		chromedp.Navigate(rig.url("")),
		poll(`!!document.querySelector('`+patternField+`')`),
		setField(patternField, "hexagonal", "input"),
		poll(barVisible()),
		clickTab("Output"),
		poll(`!!document.querySelector('[data-export-blocked]')`),
		poll(`document.querySelector('[data-export]').disabled`),
		chromedp.Evaluate(`document.querySelector('[data-export-blocked]').textContent`, &note),
		chromedp.Evaluate(yamlText, &yaml),
	)
	if !strings.Contains(note, "Save your changes") {
		t.Fatalf("note = %q", note)
	}
	if strings.Contains(yaml, "hexagonal") {
		t.Fatalf("the preview holds the draft:\n%s", yaml)
	}
	rig.run(t,
		chromedp.Click(`[data-export]`, chromedp.ByQuery),
		clickButton(saveBar, "Save"),
		poll(exportButtonEnabled()),
		poll(`document.querySelector('[data-yaml]').textContent.includes('pattern: hexagonal')`),
	)
	if contains(rig.api.called(), "export_repository_architecture") {
		t.Fatal("a disabled Export exported")
	}
}

// An export made elsewhere moves the state on the open page, through the project feed.
func TestArchitectureOutputExportStateFollowsTheProjectFeed(t *testing.T) {
	rig := newArchRig(t)
	rig.api.seed(savedRecord())
	rig.run(t,
		chromedp.EmulateViewport(1280, 900),
		chromedp.Navigate(rig.url("/file")),
		poll(`document.querySelector('[data-file-state-title]')?.textContent.trim() === 'Never exported'`),
		poll(`document.querySelector('[data-export-state]')?.textContent.trim() === 'Never exported'`),
	)
	rig.api.mu.Lock()
	rig.api.export = map[string]any{"state": "in_sync", "path": ".harness/architecture.yaml", "exported_version": 1, "exported_commit": "feedbeef000", "exported_at": "2026-10-20T10:00:00Z"}
	v := rig.api.version
	rig.api.mu.Unlock()
	rig.api.emit(map[string]any{"repository_architecture_changed": map[string]any{"repository_id": "r1", "version": v}})
	rig.run(t,
		poll(`document.querySelector('[data-file-state-title]')?.textContent.trim() === 'In sync'`),
		poll(`document.querySelector('[data-last-export]').textContent.includes('feedbee')`),
	)
}

